use amane::Color;

use super::{hex, state_home, write};
use crate::theme::oklch::{self, Oklch};
use crate::theme::{self, Theme};

/*
 * catppuccin's own colors, latte for light themes and mocha for dark ones:
 * a full rainbow, each hue hand tuned in lightness and colorfulness, which
 * no single formula matches; the wallpaper's identity lives in the
 * background, surfaces, text and comments, and in the keywords, which
 * take its hue outright; the rest of the syntax leans toward it
 */
const SLOTS: [&str; 14] = [
    "rosewater", "flamingo", "pink", "mauve", "red", "maroon", "peach",
    "yellow", "green", "teal", "sky", "sapphire", "blue", "lavender",
];

const LATTE: [u32; 14] = [
    0xdc8a78, 0xdd7878, 0xea76cb, 0x8839ef, 0xd20f39, 0xe64553, 0xfe640b,
    0xdf8e1d, 0x40a02b, 0x179299, 0x04a5e5, 0x209fb5, 0x1e66f5, 0x7287fd,
];

const MOCHA: [u32; 14] = [
    0xf5e0dc, 0xf2cdcd, 0xf5c2e7, 0xcba6f7, 0xf38ba8, 0xeba0ac, 0xfab387,
    0xf9e2af, 0xa6e3a1, 0x94e2d5, 0x89dceb, 0x74c7ec, 0x89b4fa, 0xb4befe,
];

/*
 * each hue turns toward the wallpaper's by half the way, but never more
 * than this many degrees, like material you's harmonize, and less the
 * further across the wheel it sits: hues near the wallpaper's settle into
 * it, far ones barely move, so green stays green
 */
const MAX_LEAN: f32 = 60.0;

// the palette catppuccin draws with, written as a lua table neovim reads back
pub fn export(theme: &Theme) {
    let path = format!("{}/nvim-palette.lua", state_home());

    let hue = oklch::from_color(theme.accent).hue;

    // keeps the seed's lightness and colorfulness, only its hue moves
    let lean = |seed: u32| {
        let seed = oklch::from_color(Color::rgb((seed >> 16) as u8, (seed >> 8) as u8, seed as u8));

        // the short way round the wheel
        let difference = (hue - seed.hue + 540.0).rem_euclid(360.0) - 180.0;

        // the further across the wheel, the less it may turn, so opposites keep their own hue
        let reach = MAX_LEAN * (1.0 - difference.abs() / 180.0);

        let turn = (difference / 2.0).clamp(-reach, reach);

        oklch::to_color(Oklch {
            hue: (seed.hue + turn).rem_euclid(360.0),
            ..seed
        })
    };

    let seeds = if theme.light { LATTE } else { MOCHA };

    // the signature: keywords, the color seen on every line, take the wallpaper's own hue
    let signature = |seed: u32| {
        let seed = oklch::from_color(Color::rgb((seed >> 16) as u8, (seed >> 8) as u8, seed as u8));

        oklch::to_color(Oklch { hue, ..seed })
    };

    let mut palette: Vec<(&str, Color)> = SLOTS
        .iter()
        .zip(seeds)
        .map(|(slot, seed)| {
            let color = if *slot == "mauve" { signature(seed) } else { lean(seed) };

            (*slot, color)
        })
        .collect();

    /*
     * comments, brackets and the faint parts of the editor: grey with only a
     * trace of the wallpaper's hue, so they recede behind the colored code
     */
    let grey = |lightness: f32| oklch::to_color(Oklch { lightness, chroma: 0.015, hue });

    let (comment, quiet, quieter) = if theme.light { (0.58, 0.66, 0.74) } else { (0.60, 0.52, 0.45) };

    // the background, surfaces and text are the shell's, which makes it the wallpaper's theme
    palette.extend([
        ("text", theme.text),
        ("subtext1", theme.secondary_text),
        ("subtext0", theme::mix(theme.secondary_text, theme.muted_text, 0.5)),
        ("overlay2", grey(comment)),
        ("overlay1", grey(quiet)),
        ("overlay0", grey(quieter)),
        ("surface2", theme.border),
        ("surface1", theme.selected_surface),
        ("surface0", theme.hover_surface),
        ("base", theme.background),
        ("mantle", theme.surface),
        ("crust", theme::mix(theme.surface, theme.text, 0.06)),
    ]);

    let green = palette.iter().find(|(slot, _)| *slot == "green").map(|(_, color)| *color);

    let mut lines = vec![
        String::from("-- generated by amane, do not edit"),
        String::from("return {"),
        format!("  light = {},", theme.light),
        // green is green again, so added lines and strings share it like catppuccin
        format!("  added = \"{}\",", hex(green.unwrap_or(theme.success))),
        // the shell's own colors, so the status line matches the tmux bar
        String::from("  ui = {"),
        format!("    accent = \"{}\",", hex(theme.accent)),
        format!("    on_accent = \"{}\",", hex(theme.on_accent)),
        format!("    segment = \"{}\",", hex(theme.selected_surface)),
        format!("    text = \"{}\",", hex(theme.text)),
        String::from("  },"),
        String::from("  palette = {"),
    ];

    for (slot, color) in palette {
        lines.push(format!("    {slot} = \"{}\",", hex(color)));
    }

    lines.push(String::from("  },"));
    lines.push(String::from("}"));

    write(&path, &(lines.join("\n") + "\n"));
}
