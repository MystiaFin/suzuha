use super::{hex, state_home, write};
use crate::theme::Theme;

// powerline arrows from a nerd font: solid between segments, thin inside one
const RIGHT: char = '\u{e0b0}';
const RIGHT_THIN: char = '\u{e0b1}';
const LEFT: char = '\u{e0b2}';
const LEFT_THIN: char = '\u{e0b3}';

// the status line and pane colors, sourced into every running tmux server
pub fn export(theme: &Theme) {
    let path = format!("{}/tmux-colors.conf", state_home());

    let surface = hex(theme.surface);
    let border = hex(theme.border);
    let selected = hex(theme.selected_surface);
    let text = hex(theme.text);
    let muted = hex(theme.muted_text);
    let accent = hex(theme.accent);
    let on_accent = hex(theme.on_accent);
    let danger = hex(theme.danger);

    /*
     * nord-tmux's layout with the theme's colors: the bar is the surface,
     * plain segments are the selected surface, and the session, the current
     * window and the host are the accent; each arrow is colored by the two
     * segments it joins, so it reads as the edge of a chevron
     */
    let bar = &surface;
    let segment = &selected;

    let plain = "nobold,noitalics,nounderscore";

    let status_left = format!(
        "#[fg={on_accent},bg={accent},bold] #S #[fg={accent},bg={bar},{plain}]{RIGHT}"
    );

    let status_right = format!(
        "#[fg={segment},bg={bar},{plain}]{LEFT}#[fg={text},bg={segment}] %Y-%m-%d \
         #[fg={text},bg={segment},{plain}]{LEFT_THIN}#[fg={text},bg={segment}] %H:%M \
         #[fg={accent},bg={segment},{plain}]{LEFT}#[fg={on_accent},bg={accent},bold] #H "
    );

    let window = window_format(bar, segment, &text);
    let current = window_format(bar, &accent, &on_accent);

    let lines = [
        String::from("# generated by amane, do not edit"),
        format!("set -g status-style \"bg={bar},fg={text}\""),
        format!("set -g status-left \"{status_left}\""),
        format!("set -g status-right \"{status_right}\""),
        format!("set -g window-status-format \"{window}\""),
        format!("set -g window-status-current-format \"{current}\""),
        String::from("set -g window-status-separator \"\""),
        format!("set -g message-style \"bg={selected},fg={text}\""),
        format!("set -g message-command-style \"bg={selected},fg={accent}\""),
        format!("set -g mode-style \"bg={accent},fg={on_accent},bold\""),
        format!("set -g pane-border-style \"fg={border}\""),
        format!("set -g pane-active-border-style \"fg={accent}\""),
        format!("set -g clock-mode-colour \"{accent}\""),
        format!("set -g display-panes-colour \"{muted}\""),
        format!("set -g display-panes-active-colour \"{accent}\""),
        format!("set -g window-status-bell-style \"bg={danger},fg={on_accent},bold\""),
    ];

    write(&path, &(lines.join("\n") + "\n"));

    // no server running is fine, the next one sources the file from its config
    let _ = amane::output(&format!("tmux source-file '{path}' 2>/dev/null"));
}

// a bar-colored notch cut into the left, the number and name, and an arrow out
fn window_format(bar: &str, fill: &str, ink: &str) -> String {
    let plain = "nobold,noitalics,nounderscore";

    format!(
        "#[fg={bar},bg={fill},{plain}]{RIGHT} #[fg={ink},bg={fill}]#I \
         #[fg={ink},bg={fill},{plain}]{RIGHT_THIN} #[fg={ink},bg={fill}]#W #F \
         #[fg={fill},bg={bar},{plain}]{RIGHT}"
    )
}
